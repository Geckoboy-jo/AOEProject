#!/usr/bin/env node
// Downloads the "trick" ambush paintings: famous, public-domain, absurdly
// hard to draw from memory. Edit assets/paintings/list.json to change the set.
//
// For each entry it asks Wikipedia for the article's main image (following
// redirects; falls back to a search if the title doesn't match), then
// downloads a 1600px version from Wikimedia Commons.
//
// Writes:  assets/paintings/<slug>.<ext>   the images (public domain; commit them)
//          assets/paintings/cache.js       list loaded by index.html
// Usage:   node scripts/build-paintings.js           (only fetches what's missing)
//          node scripts/build-paintings.js --fresh   (re-download everything)
// No API key needed.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "assets", "paintings");
const LIST = path.join(DIR, "list.json");
const OUT = path.join(DIR, "cache.js");
const WIDTH = 1600;
// Wikimedia asks API clients to identify themselves
const HEADERS = { "User-Agent": "GhoulleHackathonGame/1.0 (https://github.com/Geckoboy-jo/AOEProject)" };

const slug = (s) => s.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function api(params) {
  const url = "https://en.wikipedia.org/w/api.php?" + new URLSearchParams({ format: "json", formatversion: "2", ...params });
  const res = await fetch(url, { headers: HEADERS });
  if (!res.ok) throw new Error(`Wikipedia API HTTP ${res.status}`);
  return res.json();
}

// -> { article, file, thumb } or null
async function lookup(entry) {
  const pageQuery = (extra) =>
    api({ action: "query", prop: "pageimages", piprop: "thumbnail|name", pithumbsize: String(WIDTH), redirects: "1", ...extra });

  let data = await pageQuery({ titles: entry.wiki });
  let page = data.query && data.query.pages && data.query.pages[0];
  if (!page || page.missing || !page.thumbnail) {
    // fall back to the top search hit for "<title> <artist> painting"
    data = await pageQuery({ generator: "search", gsrsearch: `${entry.title} ${entry.artist} painting`, gsrlimit: "1" });
    page = data.query && data.query.pages && data.query.pages[0];
    if (page) console.log(`  (searched) "${entry.wiki}" -> "${page.title}"`);
  }
  if (!page || !page.thumbnail) return null;
  return {
    article: `https://en.wikipedia.org/wiki/${encodeURIComponent(page.title.replace(/ /g, "_"))}`,
    file: page.pageimage,
    thumb: page.thumbnail.source,
  };
}

async function main() {
  const list = JSON.parse(fs.readFileSync(LIST, "utf8"));
  const fresh = process.argv.includes("--fresh");
  const out = [];
  let failed = 0;

  for (const entry of list) {
    const id = slug(entry.title);
    const existing = fs.readdirSync(DIR).find((f) => f.startsWith(id + ".") && !f.endsWith(".js") && !f.endsWith(".json"));
    try {
      const found = await lookup(entry);
      if (!found) throw new Error("no image found");
      const ext = (path.extname(new URL(found.thumb).pathname) || ".jpg").toLowerCase();
      const fileName = existing && !fresh ? existing : `${id}${ext}`;
      if (!existing || fresh) {
        const res = await fetch(found.thumb, { headers: HEADERS });
        if (!res.ok) throw new Error(`download HTTP ${res.status}`);
        fs.writeFileSync(path.join(DIR, fileName), Buffer.from(await res.arrayBuffer()));
      }
      out.push({
        id: `painting-${id}`,
        file: `assets/paintings/${fileName}`,
        title: entry.title,
        artist: entry.artist,
        year: entry.year,
        article: found.article,
        commons: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(found.file)}`,
      });
      console.log(`  ok  ${entry.title}  <-  ${found.file}`);
    } catch (err) {
      failed++;
      console.warn(`  FAIL ${entry.title}: ${err.message}`);
    }
    await sleep(300);
  }

  fs.writeFileSync(
    OUT,
    "// Generated by scripts/build-paintings.js from assets/paintings/list.json.\n" +
      "window.PAINTINGS = " + JSON.stringify(out, null, 1) + ";\n"
  );
  console.log(`\nassets/paintings/cache.js: ${out.length} paintings${failed ? `, ${failed} failed` : ""}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
