#!/usr/bin/env node
// Caches Unsplash photos locally so development doesn't burn the
// 50 requests/hour demo limit and works offline.
//
// Writes:  assets/unsplash/<id>.jpg   the images (gitignored, share them out of band)
//          assets/unsplash/cache.js   list of photos + photographer credits
// Reads:   assets/unsplash/blocklist.json   photo ids to never add (rejects)
//
// To curate: delete a photo's entry from cache.js and add its id to
// blocklist.json, or edit its "category" to move it between trick/treat.
//
// The game uses the local file when it exists, and falls back to the
// Unsplash URL when it doesn't, so cache.js works even without the images.
//
// Usage:   node scripts/build-image-cache.js            (adds to existing cache)
//          node scripts/build-image-cache.js --fresh    (start over)
//          node scripts/build-image-cache.js --images-only  (just download missing files, 0 API calls)
// Key:     read from js/config.js, or set UNSPLASH_ACCESS_KEY in your env.
// Cost:    1 API request per query (30 photos each).

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "assets", "unsplash");
const OUT = path.join(DIR, "cache.js");
const IMAGE_WIDTH = 800; // plenty for a 3-second flash; keeps files ~100KB
const DOWNLOAD_CONCURRENCY = 6;
const PER_QUERY = 15; // per search term, so no single term floods the set (Unsplash max is 30)
const UTM = "utm_source=aoe_hackathon_drawing_game&utm_medium=referral";

function loadBrowserScript(file, globalName) {
  if (!fs.existsSync(file)) return undefined;
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, "utf8") + `;this.__out = (typeof ${globalName} !== "undefined") ? ${globalName} : undefined;`, sandbox);
  return sandbox.__out ?? sandbox.window[globalName];
}

function accessKey() {
  if (process.env.UNSPLASH_ACCESS_KEY) return process.env.UNSPLASH_ACCESS_KEY;
  const cfg = loadBrowserScript(path.join(ROOT, "js", "config.js"), "APP_CONFIG");
  return cfg && cfg.UNSPLASH_ACCESS_KEY;
}

// image downloads hit images.unsplash.com, which doesn't count toward the API limit
async function downloadMissing(photos) {
  const todo = photos.filter((p) => !fs.existsSync(path.join(DIR, `${p.id}.jpg`)));
  if (!todo.length) return console.log("All images already downloaded.");
  console.log(`Downloading ${todo.length} images to assets/unsplash/ ...`);
  let done = 0, failed = 0;
  async function worker() {
    while (todo.length) {
      const p = todo.shift();
      try {
        const url = `${p.raw}&w=${IMAGE_WIDTH}&q=80&fm=jpg&fit=max`;
        const res = await fetch(url);
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        fs.writeFileSync(path.join(DIR, `${p.id}.jpg`), Buffer.from(await res.arrayBuffer()));
        done++;
      } catch (err) {
        failed++;
        console.warn(`  ${p.id}: ${err.message}`);
      }
      process.stdout.write(`\r  ${done} downloaded${failed ? `, ${failed} failed` : ""}`);
    }
  }
  await Promise.all(Array.from({ length: DOWNLOAD_CONCURRENCY }, worker));
  console.log("");
}

function writeCache(photos) {
  const cache = { generatedAt: new Date().toISOString(), photos };
  fs.writeFileSync(
    OUT,
    "// Generated by scripts/build-image-cache.js. Photo list + credits (no API key).\n" +
      "window.IMAGE_CACHE = " + JSON.stringify(cache, null, 1) + ";\n"
  );
}

async function main() {
  fs.mkdirSync(DIR, { recursive: true });

  if (process.argv.includes("--images-only")) {
    const existing = loadBrowserScript(OUT, "IMAGE_CACHE");
    if (!existing) return console.error("No assets/unsplash/cache.js yet. Run without --images-only first.");
    return downloadMissing(existing.photos);
  }

  const key = accessKey();
  if (!key) {
    console.error("No Unsplash key. Put it in js/config.js (see js/config.example.js) or set UNSPLASH_ACCESS_KEY.");
    process.exit(1);
  }

  const groups = require(path.join(ROOT, "js", "queries.js"));
  const queries = Object.entries(groups).flatMap(([category, list]) =>
    list.map((query) => ({ category, query }))
  );
  const fresh = process.argv.includes("--fresh");
  const existing = fresh ? undefined : loadBrowserScript(OUT, "IMAGE_CACHE");
  const byId = new Map((existing?.photos || []).map((p) => [p.id, p]));
  const blockFile = path.join(DIR, "blocklist.json");
  const blocked = new Set(fs.existsSync(blockFile) ? JSON.parse(fs.readFileSync(blockFile, "utf8")) : []);
  const startCount = byId.size;

  console.log(`Fetching ${queries.length} queries x ${PER_QUERY} photos (${queries.length} API requests, ${blocked.size} blocked ids)...`);
  let remaining = "?";

  for (const { category, query } of queries) {
    const params = new URLSearchParams({
      query,
      count: String(PER_QUERY),
      content_filter: "high",
      orientation: "squarish",
    });
    const res = await fetch(`https://api.unsplash.com/photos/random?${params}`, {
      headers: { Authorization: `Client-ID ${key}`, "Accept-Version": "v1" },
    });
    remaining = res.headers.get("x-ratelimit-remaining") ?? remaining;

    if (!res.ok) {
      console.warn(`  ${query}: HTTP ${res.status}${res.status === 403 ? " (rate limited, stopping; run again in an hour)" : ""}`);
      if (res.status === 401 || res.status === 403) break;
      continue;
    }

    const photos = await res.json();
    let added = 0;
    for (const p of photos) {
      if (byId.has(p.id) || blocked.has(p.id)) continue; // keep existing entries (and their category); skip rejects
      byId.set(p.id, {
        id: p.id,
        file: `assets/unsplash/${p.id}.jpg`,
        src: p.urls.regular,
        raw: p.urls.raw,
        alt: p.alt_description || query,
        prompt: query,
        category,
        credit: { name: p.user.name, link: `${p.user.links.html}?${UTM}` },
      });
      added++;
    }
    console.log(`  [${category}] ${query}: +${added}  (rate limit left: ${remaining})`);
    if (Number(remaining) <= 1) {
      console.warn("Out of requests for this hour; saving what we have.");
      break;
    }
  }

  const photos = [...byId.values()];
  writeCache(photos);
  console.log(`\nassets/unsplash/cache.js: ${photos.length} photos (${photos.length - startCount} new).`);
  await downloadMissing(photos);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
