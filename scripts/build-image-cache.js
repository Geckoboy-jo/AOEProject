#!/usr/bin/env node
// Builds image-cache.js: a list of Unsplash photo URLs + photographer credits,
// so development doesn't burn the 50 requests/hour demo limit.
//
// Only api.unsplash.com calls count toward the limit. The images themselves
// still load from images.unsplash.com (hotlinked, as Unsplash's API rules
// require) and those requests are free. So we cache the API *responses*,
// not the image files.
//
// Usage:   node scripts/build-image-cache.js            (adds to existing cache)
//          node scripts/build-image-cache.js --fresh    (start over)
// Key:     read from config.js, or set UNSPLASH_ACCESS_KEY in your env.
// Cost:    1 API request per query (30 photos each).

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "image-cache.js");
const PER_QUERY = 30; // Unsplash max per request
const UTM = "utm_source=aoe_hackathon_drawing_game&utm_medium=referral";

function loadBrowserScript(file, globalName) {
  if (!fs.existsSync(file)) return undefined;
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, "utf8") + `;this.__out = (typeof ${globalName} !== "undefined") ? ${globalName} : undefined;`, sandbox);
  return sandbox.__out ?? sandbox.window[globalName];
}

function accessKey() {
  if (process.env.UNSPLASH_ACCESS_KEY) return process.env.UNSPLASH_ACCESS_KEY;
  const cfg = loadBrowserScript(path.join(ROOT, "config.js"), "APP_CONFIG");
  return cfg && cfg.UNSPLASH_ACCESS_KEY;
}

async function main() {
  const key = accessKey();
  if (!key) {
    console.error("No Unsplash key. Put it in config.js (see config.example.js) or set UNSPLASH_ACCESS_KEY.");
    process.exit(1);
  }

  const queries = require(path.join(ROOT, "queries.js"));
  const fresh = process.argv.includes("--fresh");
  const existing = fresh ? undefined : loadBrowserScript(OUT, "IMAGE_CACHE");
  const byId = new Map((existing?.photos || []).map((p) => [p.id, p]));
  const startCount = byId.size;

  console.log(`Fetching ${queries.length} queries x ${PER_QUERY} photos (${queries.length} API requests)...`);
  let remaining = "?";

  for (const query of queries) {
    const params = new URLSearchParams({
      query,
      count: String(PER_QUERY),
      content_filter: "high",
      orientation: "squarish",
    });
    const res = await fetch(`https://api.unsplash.com/photos/random?${params}`, {
      headers: { Authorization: `Client-ID ${key}`, "Accept-Version": "v1" },
    });
    remaining = res.headers.get("x-ratelimit-remaining") ?? remaining;

    if (!res.ok) {
      console.warn(`  ${query}: HTTP ${res.status}${res.status === 403 ? " (rate limited, stopping; run again in an hour)" : ""}`);
      if (res.status === 401 || res.status === 403) break;
      continue;
    }

    const photos = await res.json();
    let added = 0;
    for (const p of photos) {
      if (byId.has(p.id)) continue;
      byId.set(p.id, {
        id: p.id,
        src: p.urls.regular,
        alt: p.alt_description || query,
        prompt: query,
        credit: { name: p.user.name, link: `${p.user.links.html}?${UTM}` },
      });
      added++;
    }
    console.log(`  ${query}: +${added}  (rate limit left: ${remaining})`);
    if (Number(remaining) <= 1) {
      console.warn("Out of requests for this hour; saving what we have.");
      break;
    }
  }

  const cache = { generatedAt: new Date().toISOString(), photos: [...byId.values()] };
  fs.writeFileSync(
    OUT,
    "// Generated by scripts/build-image-cache.js. Unsplash URLs + credits only (no images, no API key).\n" +
      "window.IMAGE_CACHE = " + JSON.stringify(cache, null, 1) + ";\n"
  );
  console.log(`\nimage-cache.js: ${cache.photos.length} photos (${cache.photos.length - startCount} new).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
